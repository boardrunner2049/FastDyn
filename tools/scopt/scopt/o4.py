@dataclass(frozen=True)
class Decision:
    status: str                        # INCLUDED | EXCLUDED
    reason: str                        # INCLUDE_REASONS | EXCLUDE_REASONS
    evidence: str                      # docs/O4.md section, then the numbers; never empty
    params: Mapping[str, Any] = field(default_factory=lambda: MappingProxyType({}))
    enabled: bool = False              # INCLUDED default-disabled pass: O4 sets enabled = true
    arm: str | None = None             # the campaign arm that decides or decided it
    marginal: str | None = None        # the item's own effect inside O4


def _inc(reason, evidence, *, params=None, enabled=False, arm=None, marginal=None):
    return Decision(INCLUDED, reason, evidence, MappingProxyType(dict(params or {})), enabled,
                    arm, marginal)


def _exc(reason, evidence, *, params=None, arm=None, marginal=None):
    return Decision(EXCLUDED, reason, evidence, MappingProxyType(dict(params or {})), False,
                    arm, marginal)


