"""scopt O4: one recorded decision per pass, firmware mode, speed knob and runtime setting.

The rule, in the user's words: "we should have one config that include all of our good
things let's call it O4.  Do that! and O4 remains the best.  Note it down as well.
Whatever the best speed optimizations are there MUST BE included in O4~!"

``docs/O4.md`` states the rule and its three properties (Inclusion, Best, Decided);
``tests/unit/test_o4_manifest.py`` enforces Decided against this module and Best against
``docs/o4-evidence.json`` (generated by ``scripts/o4_evidence.py``).  Evidence strings
name the ``docs/O4.md`` section that holds the numbers, then the numbers themselves.
Ratios are time(reference) / time(arm); triples are packet / uart / cli; R1 and R2 are the
round-1 (/data/scfix-campaign/TIMING.md) and round-2 (/data/scfix-r2/TIMING.md) campaigns.
"""
