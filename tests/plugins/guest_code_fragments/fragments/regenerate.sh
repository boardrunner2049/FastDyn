#!/usr/bin/env bash
set -euo pipefail
root=$(cd "$(dirname "$0")" && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

arm-none-eabi-as -mcpu=cortex-a9 "$root/arm.S" -o "$tmp/arm.o"
llvm-mc -triple=aarch64-none-elf -filetype=obj "$root/a64.S" -o "$tmp/a64.o"
llvm-mc -triple=riscv64-none-elf -filetype=obj "$root/riscv.S" -o "$tmp/riscv.o"
nasm -f elf64 "$root/x86.asm" -o "$tmp/x86.o"
for obj in "$tmp"/*.o; do
    if readelf -r "$obj" | grep -q ' R_'; then
        echo "unresolved relocation in $obj" >&2
        exit 1
    fi
done

check_text() {
    local obj=$1 expected=$2 raw="$tmp/$(basename "$obj").bin" actual
    llvm-objcopy -O binary --only-section=.text "$obj" "$raw"
    actual=$(od -An -tx1 "$raw" | tr -d ' \n')
    if [[ "$actual" != "$expected" ]]; then
        echo "generated bytes changed for $obj" >&2
        echo "expected: $expected" >&2
        echo "actual:   $actual" >&2
        exit 1
    fi
}

# These are the arrays committed in runtime/guest_code_fragments.c.  ARM and
# x86 contain their two mode-specific fragments consecutively.
check_text "$tmp/arm.o"   "ff0000e2070080e200f0ff0000f10700"
check_text "$tmp/a64.o"   "001c0012001c0011"
check_text "$tmp/riscv.o" "1375f50f13057500"
check_text "$tmp/x86.o"   "25ff0083c00725ff00000083c007"
echo "PASS generated fragment bytes match the committed C fixtures and contain no relocations"
